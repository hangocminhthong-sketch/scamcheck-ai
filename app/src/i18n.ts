export type Key = keyof typeof en;
const dicts: Record<Lang, Dict> = { en, vi };

export function detectLang(saved: string | null, navLang = typeof navigator !== 'undefined' ? navigator.language : 'en'): Lang {
  if (saved === 'en' || saved === 'vi') return saved;
  return navLang.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

export function makeT(lang: Lang) {
  const d = dicts[lang];
  return {
    t(key: Key, vars: Record<string, string | number> = {}): string {
      const v = d[key];
      const s = typeof v === 'string' ? v : '';
      return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
    },
    list(key: 'steps_likely_scam' | 'steps_suspicious' | 'steps_low_risk'): string[] {
      return d[key];
    },
    has(key: string): key is Key {
      return key in d;
    },
  };
}
export type T = ReturnType<typeof makeT>;
